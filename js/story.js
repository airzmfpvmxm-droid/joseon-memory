export function chapterDialogue(id,phase,state){
 const entry=storyChapters[id-1],lines=entry[phase].map(line=>[...line]);
 if(phase==='before'&&id>1){const previous=state.notes[id-1];if(previous===0||previous===1)lines[0]=['나',`앞 장에 “${storyChapters[id-2].notes[previous].text}”라고 적었다. ${lines[0][1]}`];}
 if(phase==='after'){const selected=state.notes[id];if(selected===0||selected===1)lines.push(['나',entry.notes[selected].reply]);}
 return lines;
}
